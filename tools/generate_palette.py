"""Generate native theme roles from the same tokens used by React Native; --check detects drift."""

import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def contrast(first, second):
    def luminance(color):
        channels = [int(color[index:index + 2], 16) / 255 for index in (1, 3, 5)]
        channels = [value / 12.92 if value <= .04045 else ((value + .055) / 1.055) ** 2.4 for value in channels]
        return sum(value * weight for value, weight in zip(channels, (.2126, .7152, .0722)))
    low, high = sorted((luminance(first), luminance(second)))
    return (high + .05) / (low + .05)


def artifacts():
    tokens = json.loads((ROOT / 'src/ui/paletteTokens.json').read_text(encoding='utf-8'))
    assert 'graphite' in tokens['accents']
    keys = list(tokens['base']['light'])
    assert set(tokens['base']['dark']) == set(keys)
    kotlin = ['// Generated by tools/generate_palette.py. Edit src/ui/paletteTokens.json instead.',
              'package com.attentionstats.appearance', '', 'internal data class NativePalette(']
    kotlin += [f'    val {key}: Int,' for key in keys]
    kotlin += [')', '', 'internal object PaletteTokens {', '    fun resolve(dark: Boolean, accent: String): NativePalette =',
               '        when ((if (dark) "dark" else "light") + ":" + accent) {']
    xml = ['<!-- Generated by tools/generate_palette.py from src/ui/paletteTokens.json. -->', '<resources>']
    for accent, modes in tokens['accents'].items():
        for mode, overrides in modes.items():
            assert set(overrides) <= set(keys)
            colors = {**tokens['base'][mode], **overrides}
            assert all(re.fullmatch(r'#[0-9A-F]{6}', value) for value in colors.values())
            pairs = [(text, surface) for text in ('text', 'muted', 'faint') for surface in ('canvas', 'surface', 'surfaceAlt', 'raised')]
            pairs += [('accent', 'surface'), ('onAccent', 'accentFill'), ('onHero', 'hero'), ('heroMuted', 'hero'),
                      ('onLavender', 'lavender'), ('warn', 'warnSoft'), ('danger', 'dangerSoft')]
            for foreground, background in pairs:
                assert contrast(colors[foreground], colors[background]) >= 4.5, (mode, accent, foreground, background)
            kotlin += [f'            "{mode}:{accent}" -> NativePalette(']
            kotlin += [f'                {key} = 0xFF{colors[key][1:]}.toInt(),' for key in keys]
            kotlin += ['            )']
            suffix = '' if accent == 'blue' else accent.title()
            name = f'AttentionNative{mode.title()}{suffix}'
            parent = 'android:style/Theme.Material.Light.NoActionBar' if mode == 'light' else 'android:style/Theme.Material.NoActionBar'
            xml += [f'    <style name="{name}" parent="{parent}">']
            for role, token in [('colorAccent', 'accent'), ('windowBackground', 'canvas'), ('colorBackground', 'surface'),
                                ('colorBackgroundFloating', 'surfaceAlt'), ('navigationBarColor', 'canvas'),
                                ('statusBarColor', 'canvas'), ('textColorPrimary', 'text'), ('textColorSecondary', 'muted')]:
                xml += [f'        <item name="android:{role}">{colors[token]}</item>']
            xml += ['        <item name="android:fontFamily">sans</item>', '    </style>']
    kotlin += ['            else -> resolve(dark, "graphite")', '        }', '}']
    xml += ['</resources>']
    return {
        ROOT / 'android/app/src/main/java/com/attentionstats/appearance/PaletteTokens.kt': '\n'.join(kotlin) + '\n',
        ROOT / 'android/app/src/main/res/values/appearance_themes.xml': '\n'.join(xml) + '\n',
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, value in artifacts().items():
        if args.check:
            if not path.is_file() or path.read_text(encoding='utf-8') != value:
                raise SystemExit('Theme tokens drifted; run python tools/generate_palette.py')
        else:
            path.write_text(value, encoding='utf-8')
    print('PASS: React Native/native theme roles share one token source')


if __name__ == '__main__':
    main()
