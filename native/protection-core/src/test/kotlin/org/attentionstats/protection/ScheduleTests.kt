package org.attentionstats.protection

import java.time.ZonedDateTime

fun main() {
    var checks = 0
    fun expect(value: Boolean, label: String) { check(value) { label }; checks++ }
    val monday = 1
    val window = BlockWindow("evening", "social", monday, 19 * 60, 23 * 60, true)
    fun at(value: String) = ZonedDateTime.parse(value)
    expect(!window.active(at("2026-11-02T18:59:59+06:00")), "before start")
    expect(window.active(at("2026-11-02T19:00:00+06:00")), "inclusive start")
    expect(window.active(at("2026-11-02T22:59:59+06:00")), "inside")
    expect(!window.active(at("2026-11-02T23:00:00+06:00")), "exclusive end")
    expect(!window.active(at("2026-11-03T20:00:00+06:00")), "unselected day")
    expect(!window.copy(enabled = false).active(at("2026-11-02T20:00:00+06:00")), "disabled")
    val night = window.copy(startMinute = 23 * 60, endMinute = 7 * 60)
    expect(night.active(at("2026-11-02T23:00:00+06:00")), "overnight start")
    expect(night.active(at("2026-11-03T06:59:00+06:00")), "previous start weekday")
    expect(!night.active(at("2026-11-02T06:59:00+06:00")), "no unselected Sunday carry")
    expect(!night.active(at("2026-11-03T07:00:00+06:00")), "overnight end")
    val sunday = night.copy(days = 64)
    expect(sunday.active(at("2026-11-02T06:00:00+06:00")), "Sunday to Monday wrap")
    val dst = night.copy(days = 64, startMinute = 60, endMinute = 180)
    expect(dst.active(at("2026-11-01T01:30:00-04:00[America/New_York]")), "first repeated hour")
    expect(dst.active(at("2026-11-01T01:30:00-05:00[America/New_York]")), "second repeated hour")
    val excluded = setOf("com.example.recovery")
    val group = AppGroup("social", "Social", setOf("com.example.social", "com.example.media"))
    val plan = SchedulePlan(listOf(group), listOf(window, window.copy(id = "lunch", startMinute = 720, endMinute = 780)))
    plan.validate(excluded)
    expect(plan.matching("com.example.social", at("2026-11-02T20:00:00+06:00"), excluded).size == 1, "group match")
    expect(plan.matching("com.example.media", at("2026-11-02T12:30:00+06:00"), excluded).size == 1, "second app and window")
    expect(plan.matching("com.example.other", at("2026-11-02T20:00:00+06:00"), excluded).isEmpty(), "unselected app")
    expect(plan.matching("com.example.social", at("2026-11-02T20:00:00+06:00"), setOf("com.example.social")).isEmpty(), "invariant exclusion")
    expect(plan.targets() == group.packages, "event targets only enabled groups")
    fun rejects(value: SchedulePlan, label: String) { expect(runCatching { value.validate(excluded) }.isFailure, label) }
    rejects(plan.copy(windows = listOf(window.copy(startMinute = 1380, endMinute = 1380))), "ambiguous full day")
    rejects(plan.copy(windows = listOf(window.copy(days = 0))), "empty weekdays")
    rejects(plan.copy(windows = listOf(window.copy(groupId = "missing"))), "orphan window")
    rejects(plan.copy(groups = listOf(group, group)), "duplicate group")
    rejects(plan.copy(windows = listOf(window, window)), "duplicate window")
    rejects(plan.copy(groups = listOf(group.copy(packages = excluded))), "recovery cannot be targeted")
    rejects(plan.copy(windows = listOf(window.copy(endMinute = 1440))), "invalid minute")
    rejects(plan.copy(groups = listOf(group.copy(packages = emptySet()))), "empty group")
    expect(plan.copy(windows = listOf(window.copy(enabled = false))).targets().isEmpty(), "disabled no events")
    val shorts = window.copy(id = "shorts", scope = BlockScope.SHORT_VIDEOS)
    val combined = plan.copy(windows = listOf(window, shorts))
    expect(combined.matching("com.example.social", at("2026-11-02T20:00:00+06:00"), excluded) == listOf(window), "whole-app rules never include selective rules")
    expect(combined.matching("com.example.social", at("2026-11-02T20:00:00+06:00"), excluded, BlockScope.SHORT_VIDEOS) == listOf(shorts), "selective scope isolated")
    val fullDay = window.copy(startMinute = 0, endMinute = 0, allDay = true)
    plan.copy(windows = listOf(fullDay)).validate(excluded)
    expect(fullDay.active(at("2026-11-02T00:00:00+06:00")), "all-day inclusive midnight")
    expect(fullDay.active(at("2026-11-02T23:59:59+06:00")), "all-day last minute")
    expect(!fullDay.active(at("2026-11-03T00:00:00+06:00")), "all-day unselected next day")
    rejects(plan.copy(windows = listOf(fullDay.copy(endMinute = 1))), "all-day canonical time")
    val morning = window.copy(id = "morning", startMinute = 300, endMinute = 660)
    val evening = window.copy(id = "evening", startMinute = 1080, endMinute = 1380)
    val split = plan.copy(windows = listOf(morning, evening))
    expect(split.matching("com.example.social", at("2026-11-02T05:00:00+06:00"), excluded) == listOf(morning), "requested morning start")
    expect(split.matching("com.example.social", at("2026-11-02T11:00:00+06:00"), excluded).isEmpty(), "requested morning end")
    expect(split.matching("com.example.social", at("2026-11-02T18:00:00+06:00"), excluded) == listOf(evening), "requested evening start")
    expect(split.matching("com.example.social", at("2026-11-02T23:00:00+06:00"), excluded).isEmpty(), "requested evening end")
    val prompt = InterventionSession(10_000)
    expect(!prompt.choose(0, false), "unattached prompt cannot act")
    prompt.start(100)
    expect(prompt.remainingSeconds(100) == 10, "initial countdown")
    expect(!prompt.choose(10_099, true), "secondary gated through deadline")
    expect(prompt.remainingSeconds(25_100) == 0, "delayed callback uses elapsed time")
    expect(prompt.choose(25_100, true), "secondary unlocks after delayed tick")
    expect(!prompt.choose(25_101, false), "opposite action cannot fire after choice")
    expect(!prompt.choose(25_102, true), "repeated action ignored")
    val immediate = InterventionSession(30_000).also { it.start(0) }
    expect(immediate.choose(0, false), "primary always available during wait")
    val detached = InterventionSession(0).also { it.start(0); it.finish(); it.start(1) }
    expect(!detached.choose(1, false), "detached prompt cannot resurrect")
    val boundary = InterventionSession(3_000).also { it.start(0); it.start(2_000) }
    expect(boundary.remainingSeconds(2_999) == 1 && boundary.choose(3_000, true), "reattach cannot restart deadline")
    val outcomes = mutableListOf<Pair<String, String>>()
    val earlyChoice = InterventionOutcome { id, choice -> outcomes.add(id to choice) }
    earlyChoice.choose("continued")
    expect(outcomes.isEmpty(), "choice waits for persisted ID")
    earlyChoice.recorded("first"); earlyChoice.recorded("duplicate"); earlyChoice.choose("left")
    expect(outcomes == listOf("first" to "continued"), "late ID retains original choice exactly once")
    val earlyId = InterventionOutcome { id, choice -> outcomes.add(id to choice) }
    earlyId.recorded("second")
    expect(outcomes.size == 1, "recording alone is not a decision")
    earlyId.choose("left"); earlyId.choose("continued"); earlyId.recorded("second")
    expect(outcomes.last() == "second" to "left" && outcomes.size == 2, "persisted ID then choice resolves once")
    expect(PlaybackPausePolicy.classify("instagram", "clips_pause_button", "Pause") == PauseControlState.PLAYING, "known explicit Pause control")
    expect(PlaybackPausePolicy.classify("instagram", "clips_pause_button", "Play") == PauseControlState.PAUSED, "already-paused control never requests a toggle")
    expect(PlaybackPausePolicy.classify("instagram", "caption", "Pause") == PauseControlState.UNKNOWN, "content text cannot authorize a click")
    expect(PlaybackPausePolicy.classify("instagram", "clips_pause_button", "Play/Pause") == PauseControlState.UNKNOWN, "ambiguous toggle cannot authorize a click")
    expect(PlaybackPausePolicy.classify("tiktok", "clips_pause_button", "Pause") == PauseControlState.UNKNOWN, "no cross-source pause assumption")
    expect(PlaybackPausePolicy.classify("instagram", null, null) == PauseControlState.UNKNOWN, "missing controls use accessible fallback")
    val focus = FocusSession("focus-test", setOf("com.example.social"), 1_000_000, 1_060_000, 100, 60_100, 3)
    focus.validate(excluded)
    expect(focus.remaining(1_000_000, 100, 3) == 60_000L, "focus starts at full duration")
    expect(focus.remaining(10, 30_100, 3) == 30_000L, "same-boot rollback does not extend focus")
    expect(focus.remaining(Long.MAX_VALUE, 30_100, 3) == 30_000L, "same-boot forward clock does not end focus")
    expect(focus.remaining(1_060_000, 60_100, 3) == 0L, "focus exclusive elapsed deadline")
    expect(focus.remaining(1_060_001, 60_101, 3) == 0L, "expired focus stays expired")
    expect(focus.remaining(1_000_000, 99, 3) == 0L, "elapsed rollback fails open")
    expect(focus.remaining(1_030_000, 5, 4) == 30_000L, "reboot bounded UTC fallback")
    expect(focus.remaining(999_999, 5, 4) == 0L, "reboot wall rollback fails open")
    expect(focus.remaining(1_060_000, 5, 4) == 0L, "reboot expired deadline fails open")
    expect(focus.remaining(1_030_000, 5, -1) == 0L, "unknown boot fails open")
    expect(focus.remaining(1_030_000, 5, 2) == 0L, "earlier boot fails open")
    fun invalidFocus(value: FocusSession, label: String) = expect(runCatching { value.validate(excluded) }.isFailure, label)
    invalidFocus(focus.copy(packages = excluded), "focus cannot target recovery apps")
    invalidFocus(focus.copy(deadlineMs = focus.startedMs), "zero-duration focus rejected")
    invalidFocus(focus.copy(elapsedDeadline = 60_101), "inconsistent focus deadlines rejected")
    invalidFocus(focus.copy(deadlineMs = 1_000_001), "fractional minute focus rejected")
    invalidFocus(focus.copy(boot = -1), "unknown boot cannot start focus")
    invalidFocus(focus.copy(packages = emptySet()), "empty focus targets rejected")
    println("PASS: $checks schedule boundary, overlap, validation and recovery checks")
}
